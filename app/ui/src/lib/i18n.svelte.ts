const dictionaries: Record<string, Record<Key, string>> = { en, fr };
export const LANGUAGES = [
  { code: "en", name: "English" },
  { code: "fr", name: "Français" },
];

function detect(): string {
  const nav = typeof navigator !== "undefined" ? navigator.language : "en";
  return nav.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export const locale = $state({ lang: detect() });

/** Sets the language; `null` follows the system. */
export function setLanguage(code: string | null) {
  locale.lang = code && dictionaries[code] ? code : detect();
  document.documentElement.lang = locale.lang;
}

export function t(key: Key, params?: Record<string, string | number>): string {
  let s: string = dictionaries[locale.lang]?.[key] ?? en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  }
  return s;
}
